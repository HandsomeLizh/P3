#!/usr/bin/env bash
# Replay a recorded capture bag (sensors + /car/pose + /sensor/meta, e.g. Env_X/InterFace/bags/*)
# through the full P3 pipeline, then score against truth. Variants:
#   --imu off --wheel on   (default wheel) wheel-speed output gate, no IMU
#   --imu on               wheel gate + synthetic IMU (optional extra)
#   --imu off --wheel off  plain 360 deg baseline
# Isolated ROS domain (default 91, localhost only), headless, real-time rate.
#   replay_sensor_bag.sh <bag_dir> --imu on|off [--wheel on|off] [--noise mems|none]
#                        [--frames N] [--domain 91]
# Output: results/replay_<bag>_imu<on|off>_wheel<on|off>_<time>/ with truth_eval.json.
# Requires that no other P3 run is active in this workspace (control.py enforces one run).
set -eo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
BAG="$(realpath "${1:?usage: replay_sensor_bag.sh <bag_dir> --imu on|off [--wheel on|off]}")"; shift
IMU=''; WHEEL=on; NOISE=mems; FRAMES=0; DOMAIN=91
while [[ $# -gt 0 ]]; do
  case "$1" in
    --imu) IMU="$2"; shift 2;;
    --wheel) WHEEL="$2"; shift 2;;
    --noise) NOISE="$2"; shift 2;;
    --frames) FRAMES="$2"; shift 2;;
    --domain) DOMAIN="$2"; shift 2;;
    *) echo "unknown argument $1" >&2; exit 2;;
  esac
done
[[ "$IMU" == on || "$IMU" == off ]] || { echo "--imu on|off is required" >&2; exit 2; }
[[ "$WHEEL" == on || "$WHEEL" == off ]] || { echo "--wheel must be on or off" >&2; exit 2; }
NAME="$(basename "$BAG")"
source "$ROOT/scripts/env.sh" >/dev/null
export ROS_DOMAIN_ID=$DOMAIN ROS_LOCALHOST_ONLY=1

# 1. Test-only index for scripts/replay_bag.py (segment files in numeric order).
INDEX="$ROOT/results/bag_inputs/$NAME"
if [[ ! -f "$INDEX/metadata.yaml" ]]; then
  mkdir -p "$INDEX"
  for f in "$BAG"/*.db3; do ln -sf "$f" "$INDEX/"; done
  { echo "# Test-only index for scripts/replay_bag.py, generated by scripts/sim_imu/replay_sensor_bag.sh."
    echo "rosbag2_bagfile_information:"; echo "  version: 5"; echo "  storage_identifier: sqlite3"
    echo "  relative_file_paths:"
    ls "$BAG"/*.db3 | xargs -n1 basename | sort -t_ -k3 -n | sed 's/^/    - /'; } > "$INDEX/metadata.yaml"
fi

# 2. Synthetic IMU and evaluation truth from the same bag (cached; truth is identical for any noise).
CACHE="$ROOT/results/sim_imu_bags"; mkdir -p "$CACHE"
NPZ="$CACHE/${NAME}_${NOISE}"
[[ -f "$NPZ.npz" ]] || nice -n 10 /usr/bin/python3 "$HERE/build_sim_imu.py" --truth "$BAG" --noise "$NOISE" \
  --out "$NPZ" > "$NPZ.log" 2>&1 || { echo "IMU build failed, see $NPZ.log"; exit 1; }

# 3. Replay. The simimu profile already contains the wheel gate; IMU is the optional extra.
if [[ "$IMU" == on ]]; then PROFILE="$ROOT/config/simulation_lidar_360_simimu.yaml"; WHEEL=on
elif [[ "$WHEEL" == on ]]; then PROFILE="$ROOT/config/simulation_lidar_360_wheel.yaml"
else PROFILE="$ROOT/config/simulation_lidar_360.yaml"; fi
OUT="$ROOT/results/replay_${NAME}_imu${IMU}_wheel${WHEEL}_$(date +%Y%m%d_%H%M%S)"
/usr/bin/python3 "$ROOT/scripts/control.py" start --profile "$PROFILE" --bag "$INDEX" --frames "$FRAMES" \
  --domain "$DOMAIN" --output "$OUT"
cp "$ROOT/build_manifest.json" "$OUT/build_manifest.json"
players=()
cleanup() {
  trap - EXIT INT TERM
  for pid in "${players[@]}"; do kill -INT "$pid" 2>/dev/null || true; done
  timeout 120 "$ROOT/save_map.sh" > "$OUT/replay_cleanup.log" 2>&1 || true
  "$ROOT/stop.sh" >> "$OUT/replay_cleanup.log" 2>&1 || true
}
trap cleanup EXIT
trap 'exit 130' INT TERM
if [[ "$IMU" == on ]]; then
  # Straight to VoxelMap: the Python sensor adapter drops bursts of a 100 Hz best-effort stream.
  /usr/bin/python3 "$HERE/sim_imu_player.py" "$NPZ.npz" --topic /fusion/imu --frame-id imu \
    --timeline "$OUT/replay_frames.csv" > "$OUT/sim_imu_player.log" 2>&1 &
  players+=($!)
fi
if [[ "$WHEEL" == on ]]; then
  # Subshell with the Env_X overlay: only the player needs the VehicleTelemetry type.
  ( source /home/yanfa/Env_X/InterFace/install/setup.bash && exec /usr/bin/python3 \
      "$HERE/wheel_speed_player.py" "$BAG" --timeline "$OUT/replay_frames.csv" ) \
    > "$OUT/wheel_speed_player.log" 2>&1 &
  players+=($!)
fi
echo "Replaying $NAME (IMU $IMU, wheel $WHEEL, noise $NOISE) -> $OUT"
while "$ROOT/status.sh" 2>/dev/null | grep -q '^player RUNNING'; do sleep 10; done
sleep 30   # let the pose-settle interval and the mapping queue drain
cleanup
nice -n 10 /usr/bin/python3 "$HERE/evaluate_against_truth.py" --run "$OUT" --truth "$NPZ.npz" \
  --out "$OUT/truth_eval.json" > /dev/null && echo "Evaluation: $OUT/truth_eval.json"
echo "Results: $OUT"
